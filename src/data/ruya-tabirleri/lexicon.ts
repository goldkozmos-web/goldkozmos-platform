function titleCase(value: string) {
  return value
    .split(" ")
    .map((part) => part.charAt(0).toLocaleUpperCase("tr-TR") + part.slice(1))
    .join(" ");
}

function slugify(value: string) {
  return foldTurkish(value).replace(/\s+/g, "-");
}

function entry(
  title: string,
  aliases: string[] = [],
  keywords: string[] = [],
  contentSlug?: string,
): DreamLexiconEntry {
  const slug = slugify(title);
  const allAliases = uniqueTerms([title, ...aliases]);
  const allKeywords = uniqueTerms(keywords);
  return {
    title,
    slug,
    aliases: allAliases,
    keywords: allKeywords,
    normalizedSearchTerms: uniqueTerms(
      [...allAliases, ...allKeywords, slug.replaceAll("-", " ")].map(foldTurkish),
    ),
    contentSlug,
  };
}

function see(noun: string, aliases: string[] = [], keywords: string[] = [], contentSlug?: string) {
  const named = titleCase(noun);
  return entry(
    `Rüyada ${named} Görmek`,
    [
      noun,
      `${noun} görmek`,
      `${noun} gördüm`,
      `rüyada ${noun}`,
      `rüyada ${noun} görmek`,
      `rüyada ${noun} gördüm`,
      ...aliases,
    ],
    keywords,
    contentSlug,
  );
}

function act(verb: string, aliases: string[] = [], keywords: string[] = [], contentSlug?: string) {
  const named = titleCase(verb);
  return entry(
    `Rüyada ${named}`,
    [
      verb,
      `${verb} görmek`,
      `rüyada ${verb}`,
      ...aliases,
    ],
    keywords,
    contentSlug,
  );
}

